import hu.blackbelt.judo.psm.generator.sdk.core.test.guice.CastingFunctionsDaoModules;
import hu.blackbelt.judo.runtime.core.jsl.fixture.JudoRuntimeExtension;
import hu.blackbelt.judo.runtime.core.jsl.fixture.JudoRuntimeFixture;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.RegisterExtension;

import java.io.File;

import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Test plan TP-27 (jsl-itest suite in strict load): the models generated by the workflow plugin include the
 * {@code <name>-query.model} file, and the fixture's {@code QueryFactory} comes from {@code QueryModelLoadOrBuild}: in the
 * {@code query-model-load} surefire execution (strict {@code load}, no fallback) the class would fail to boot without a usable
 * query file; the whole suite runs in both modes. See change: persisted-query-model.
 */
public class PersistedQueryModelFixtureTest {

    @RegisterExtension
    static JudoRuntimeExtension runtimeExtension = new JudoRuntimeExtension("CastingFunctions", new CastingFunctionsDaoModules());

    @Test
    void generatedModelsIncludeTheQueryFile(JudoRuntimeFixture runtime) {
        final File queryFile = new File(JudoRuntimeFixture.MODEL_SOURCES, "CastingFunctions-query.model");
        assertTrue(queryFile.isFile(), "The workflow plugin did not generate " + queryFile);
        assertTrue(queryFile.length() > 0, "Empty " + queryFile);
        assertNotNull(runtime.modelHolder.getPersistedQueryModel(), "The loader did not locate the query file");
        assertNotNull(runtime.modelHolder.getAsmDigest(), "No digest of the ASM file: the saved query model cannot be validated");
        assertNotNull(runtime.modelHolder.getExpressionDigest(), "No digest of the expression file");
    }
}
